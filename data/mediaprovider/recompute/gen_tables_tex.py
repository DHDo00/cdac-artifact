#!/usr/bin/env python3
"""Generate tables_replacement.tex and the short CN/EN result paragraphs from the
recomputed pooled summaries. Labels are kept as instructed; captions state the
real boot count and per-condition request count."""
import csv, sys
from pathlib import Path

def load(p):
    with open(p) as f:
        return list(csv.DictReader(f))

def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else "39_mediaprovider_matrix_replication_20261029_230000")
    t7 = load(root / "summary/table7_pooled.csv")
    t8 = load(root / "summary/table8_pooled.csv")
    d7 = {r["condition"]: r for r in t7}
    d8 = {r["condition"]: r for r in t8}
    rows7 = ["no_rule_ax","no_rule_bx","ma_ax","ma_bx","ma_ay","mb_bx","mb_ax","mb_by","revoke_ax","revoke_bx"]
    rows8 = ["no_rule_r","no_rule_w","lw_r","lw_w","lr_r","lr_w","revoke_r","revoke_w"]
    def fmt(d, c):
        r = d[c]
        return f"{c} & {r['planned']} & {r['attempted']} & {r['usable']} & {r['cdac_denied']} & {r['other_failure']} & {r['unresolved']}"
    lines = []
    lines.append("% Candidate replacement tables for the MediaProvider functional replication (round 39).")
    lines.append("% Generated by recompute/gen_tables_tex.py from summary/*_pooled.csv;")
    lines.append("% do NOT edit the main paper with this file.")
    lines.append("")
    lines.append("\\begin{table}[t]")
    lines.append("\\caption{Caller--object selectivity for the reviewed \\codepath{MediaProvider} route")
    lines.append("($6/501$, \\codepath{openFile}). Three real guest boots, 20 cycles per boot,")
    lines.append("one request per cell per cycle (60 planned per condition).}")
    lines.append("\\label{tab:media-selectivity}")
    lines.append("\\centering")
    lines.append("\\begin{tabular}{lcccccc}")
    lines.append("\\toprule")
    lines.append("Condition & Planned & Attempted & Usable & CDAC-denied & Other fail & Unresolved \\\\")
    lines.append("\\midrule")
    label7 = {
        "no_rule_ax": "no rule, A$\\to$X", "no_rule_bx": "no rule, B$\\to$X",
        "ma_ax": "rule caller=A, A$\\to$X", "ma_bx": "rule caller=A, B$\\to$X", "ma_ay": "rule caller=A, A$\\to$Y",
        "mb_bx": "rule caller=B, B$\\to$X", "mb_ax": "rule caller=B, A$\\to$X", "mb_by": "rule caller=B, B$\\to$Y",
        "revoke_ax": "revoked, A$\\to$X", "revoke_bx": "revoked, B$\\to$X",
    }
    for c in rows7:
        r = d7[c]
        lines.append(f"{label7[c]} & {r['planned']} & {r['attempted']} & {r['usable']} & {r['cdac_denied']} & {r['other_failure']} & {r['unresolved']} \\\\")
    tot = d7["TOTAL"]
    lines.append("\\midrule")
    lines.append(f"Total & {tot['planned']} & {tot['attempted']} & {tot['usable']} & {tot['cdac_denied']} & {tot['other_failure']} & {tot['unresolved']} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append("\\begin{table}[t]")
    lines.append("\\caption{Published method-label selectivity on $6/501$ for caller $A$ and object $X$.")
    lines.append("Three real guest boots, 20 cycles per boot, one request per cell per cycle")
    lines.append("(60 planned per condition). The two target rules differ only in the")
    lines.append("\\codepath{operation} method-label selector; effective access-flag masks are off.")
    lines.append("}")
    lines.append("\\label{tab:media-method-selectivity}")
    lines.append("\\centering")
    lines.append("\\begin{tabular}{lcccccc}")
    lines.append("\\toprule")
    lines.append("Condition & Planned & Attempted & Usable & CDAC-denied & Other fail & Unresolved \\\\")
    lines.append("\\midrule")
    label8 = {
        "no_rule_r": "no rule, \\codepath{openFile}/r", "no_rule_w": "no rule, \\codepath{openAssetFile}/w",
        "lw_r": "select \\codepath{openAssetFile}, /r", "lw_w": "select \\codepath{openAssetFile}, /w",
        "lr_r": "select \\codepath{openFile}, /r", "lr_w": "select \\codepath{openFile}, /w",
        "revoke_r": "revoked, /r", "revoke_w": "revoked, /w",
    }
    for c in rows8:
        r = d8[c]
        lines.append(f"{label8[c]} & {r['planned']} & {r['attempted']} & {r['usable']} & {r['cdac_denied']} & {r['other_failure']} & {r['unresolved']} \\\\")
    tot = d8["TOTAL"]
    lines.append("\\midrule")
    lines.append(f"Total & {tot['planned']} & {tot['attempted']} & {tot['usable']} & {tot['cdac_denied']} & {tot['other_failure']} & {tot['unresolved']} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    m_den = d7["TOTAL"]["cdac_denied"]; m_use = d7["TOTAL"]["usable"]
    l_den = d8["TOTAL"]["cdac_denied"]; l_use = d8["TOTAL"]["usable"]
    lines.append("% ---- short result paragraph (CN) ----")
    lines.append(f"% 在 3 个真实 guest 启动上，MediaProvider 6/501 路由的调用者-对象矩阵共 600 次计划请求，")
    lines.append(f"% 其中 {m_den} 次目标拒绝全部对应 CDAC 匹配与执法，{m_use} 次允许/恢复均实际使用返回的描述符；")
    lines.append(f"% 方法标签矩阵共 480 次计划请求，{l_den} 次目标拒绝、{l_use} 次允许/恢复，")
    lines.append(f"% 两条规则仅改变 operation 标签选择器且有效访问标志掩码关闭。")
    lines.append("% ---- short result paragraph (EN) ----")
    lines.append(f"% Across 3 real guest boots, the caller-object matrix on the MediaProvider 6/501 route planned 600 requests:")
    lines.append(f"% {m_den} target denials each carry CDAC match-and-enforcement evidence and {m_use} allow/recovery")
    lines.append(f"% requests actually used the returned descriptor. The method-label matrix planned 480 requests:")
    lines.append(f"% {l_den} target denials and {l_use} allow/recovery requests; the two rules differ only in the")
    lines.append(f"% operation label selector with effective access-flag masks disabled.")
    (root / "tables_replacement.tex").write_text("\n".join(lines) + "\n")
    print("wrote", root / "tables_replacement.tex")

if __name__ == "__main__":
    main()
